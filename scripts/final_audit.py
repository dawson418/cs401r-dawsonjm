import json, os, re, subprocess, pandas as pd
EV = "docs/lab3-evidence"
ok = lambda c, m: print(("PASS  " if c else "FAIL  ") + m)
rd = lambda p: open(p, encoding="utf-8", errors="ignore").read() if os.path.exists(p) else ""
sh = lambda *a: subprocess.run(a, capture_output=True, text=True).stdout.strip()
log = rd(f"{EV}/train-final.log"); m = json.load(open(f"{EV}/evaluation_metrics.json"))
ok(re.search(r"Athena QueryExecutionId: [0-9a-f-]{36}", log) is not None, "T1 Athena query ID in graded log")
ok("(PendingManualApproval)" in log and "Training XGBoost with params:" in log, "T1/T4 registered + params line in log")
ok(m["precision_top10"] >= .5 and m["recall_top10"] >= .25 and m["lift_ci_low"] > 0, "T1 gates met")
rep = rd("docs/lab3-evaluation-report.md")
ok(str(m["auc_roc"]) in rep and "Slice discussion" in rep and "too small" in rep.lower(), "T1 report: numbers, slice discussion, too-small tier")
sl = pd.read_csv(f"{EV}/slice-evaluation.csv")
ok(len(sl) == 4 and {"tier", "n", "positives", "auc", "recall", "too_small"} <= set(sl.columns), "T1 slice csv")
nb = json.load(open("notebooks/lab3-demo.ipynb")); cells = [c for c in nb["cells"] if c["cell_type"] == "code"]
ok([c.get("execution_count") for c in cells] == list(range(1, len(cells) + 1)), "T2 notebook counts 1..n")
ok(not [o for c in cells for o in c.get("outputs", []) if o.get("output_type") == "error"], "T2 notebook has no errors")
r = pd.read_csv(f"{EV}/rag_eval.csv")
ok(r.groupby("config").run.nunique().min() >= 2 and r.judge_model.notna().all(), "T2 rag_eval: >=2 runs per config, judge named")
ok(not r[["faithfulness", "answer_relevancy", "context_recall"]].isna().any().any(), "T2 rag_eval: no NaN")
ev = rd(f"{EV}/rag-evaluation.md")
ok(all(k in ev for k in ["Faithfulness", "Answer relevancy", "Context recall", "BEFORE"]) and "sentence by sentence" not in ev, "T2 limits + before/after, no placeholder")
ex = rd(f"{EV}/track-b-examples.md")
ok(len(re.findall(r"### Example \d", ex)) == 5 and "Observed failure 2" in ex and "Observed failure during development" in ex, "T2 five examples + two failures")
ok(ex.count("Proposed fix") >= 2 or ex.count("Fix applied") >= 1, "T2 failures have fixes")
d = rd("docs/lab3-model-design.md"); words = len(d.split())
ok("Track B" in d[:300] and all(k in d for k in ["Churn model", "What the features bought", "LLM system", "10x"]), "T3 declared + sections")
print(f"      design doc words (incl. headings): {words}  (target ~700)")
ok(rd("docs/bedrock-access-verification.txt").count("PASS") >= 2, "T4 bedrock verification: 2 PASS")
ok(bool(rd("docs/lab3-teardown-output.txt")), "T4 teardown output present"); ok("Lab 3" in rd("README.md"), "T4 README")
ok("early-stopping-rounds" in rd("models/churn/train.py"), "T4 no literal in training call")
ok(not [f for f in sh("git", "ls-files").splitlines() if re.search(r"\.env$|\.tfvars$|\.pem$|\.venv/", f)], "no secrets or .venv tracked")
ok(sh("git", "status", "--porcelain") == "", "git tree clean")
ok(sh("git", "rev-parse", "lab3-submit^{commit}") == sh("git", "rev-parse", "HEAD"), "tag lab3-submit == HEAD")
ok(bool(sh("git", "ls-remote", "--tags", "origin", "lab3-submit")), "tag pushed to origin")
